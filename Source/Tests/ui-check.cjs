const {chromium}=require('playwright');
const path=require('path');
const fs=require('fs');
const {pathToFileURL}=require('node:url');
const root=path.resolve(__dirname,'../..');
fs.mkdirSync(path.join(root,'qa'),{recursive:true});
process.chdir(root);
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.ORBIT_CHROME_PATH||undefined,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1360,height:950},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 const file=pathToFileURL(path.join(root,'engine/Extensions/Orbit/ui/index.html')).href;
 await page.goto(file+'?demo=1');await page.locator('[data-section="all"]').click();await page.waitForSelector('.game-card');await page.waitForTimeout(500);
 assert.equal(await page.locator('.game-card').count(),12);
 assert.equal(await page.locator('#count').textContent(),'12');
 await page.screenshot({path:'qa/Orbit-library.png'});
 const witcher=page.locator('.game-card').filter({has:page.locator('.game-title',{hasText:'The Witcher'})});
 assert.match(await witcher.locator('.store-button').textContent(),/Steam/);
 await witcher.locator('.store-button').click();await page.locator('#popover .store-option').filter({hasText:'GOG'}).click();
 assert.match(await witcher.locator('.store-button').textContent(),/GOG/);
 await page.locator('[data-view="list"]').click();assert.equal(await page.locator('.game-row').count(),12);
 await page.screenshot({path:'qa/Orbit-list.png'});
 await page.locator('#search').fill('CYBERPUNK');assert.equal(await page.locator('.game-row').count(),1);
 await page.locator('#search').fill('not a real game');assert.equal(await page.locator('.game-row').count(),0);assert.equal(await page.locator('#empty').isVisible(),true);
 await page.locator('[data-cmd="reset"]').click();
 await page.locator('[data-view="grid"]').click();
 await page.locator('.game-card').filter({has:page.locator('.game-title',{hasText:'Hogwarts'})}).locator('.poster').click();
 await page.screenshot({path:'qa/Orbit-detail.png'});
 await page.locator('#modal .store-button').click();await page.locator('#popover .store-option').filter({hasText:'Epic Games'}).click();
 assert.match(await page.locator('#modal .primary').textContent(),/Установить/);
 await page.locator('#modal .primary').click();assert.equal(await page.locator('#install-path').inputValue(),'D:\\Games\\Hogwarts Legacy');
 await page.screenshot({path:'qa/Orbit-install.png'});
 await page.keyboard.press('Escape');await page.locator('.nav-item[data-cmd="accounts"]').click();assert.equal(await page.locator('.account').count(),6);await page.screenshot({path:'qa/Orbit-accounts.png'});await page.keyboard.press('Escape');
 await page.locator('[data-cmd="settings"]').click();await page.locator('[data-cmd="motion"]').click();assert.equal(await page.locator('html').evaluate(el=>el.classList.contains('motion-off')),true);await page.keyboard.press('Escape');
 await page.locator('[data-section="favorite"]').click();assert.equal(await page.locator('.game-card').count(),3);
 await page.locator('[data-cmd="leaveDemo"]').click();assert.equal(await page.locator('#welcome').isVisible(),true);assert.equal(await page.locator('.game-card').count(),0);await page.screenshot({path:'qa/Orbit-welcome.png'});
 await page.setViewportSize({width:900,height:700});await page.locator('[data-cmd="demo"]').click();await page.waitForTimeout(100);await page.screenshot({path:'qa/Orbit-small.png'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);console.log('UI PASS: 12 grouped games, Steam priority, provider switch, grid/list, search, empty state, install dialog, six accounts, reduced motion, favorites, demo isolation, 900px viewport.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
