const {chromium}=require('playwright');
const path=require('node:path'),assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const root=path.resolve(process.env.ORBIT_TEST_UI_ROOT||path.join(__dirname,'../..'));
const file=pathToFileURL(path.join(root,'engine/Extensions/Orbit/ui/index.html')).href;
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.ORBIT_CHROME_PATH,args:['--no-sandbox']});
 try{
  const page=await browser.newPage({viewport:{width:1360,height:950}}),errors=[];
  page.on('pageerror',e=>errors.push(String(e)));
  await page.addInitScript(()=>{window.sent=[];window.CefSharp={PostMessage:s=>sent.push(JSON.parse(s))};});
  await page.goto(file);
  const receive=m=>page.evaluate(m=>Orbit.receive(m),m);
  const last=kind=>page.evaluate(kind=>sent.filter(x=>x.kind===kind).at(-1),kind);
  const close=async()=>{await page.keyboard.press('Escape');await page.waitForSelector('#modal-backdrop',{state:'hidden'});};
  await receive({kind:'snapshot',data:{games:[],prefs:{},stores:[],downloads:[],notifications:[]}});
  await page.waitForSelector('#app-splash',{state:'detached'});
  await page.locator('[data-section="minecraft"]').click();
  const mc={settings:{askRadmin:true,packFolder:'D:\\Old Packs'},profiles:[{id:'prism-a',source:'prism',name:'Наш мир',version:'1.21',loader:'Fabric',launchable:true}],packs:[],prismAvailable:true};
  await receive({kind:'mcState',requestId:(await last('mcScan')).requestId,...mc});
  await page.locator('[data-hz="horizon"]').click();
  const hz={available:true,packFolder:'D:\\Old Packs',packs:[],hmods:[],home:'D:\\Horizon'};
  await receive({kind:'hzState',requestId:(await last('hzScan')).requestId,...hz});
  // A response for the old catalogue must not reappear after a filter change.
  const result=requestId=>({kind:'hzResult',requestId,action:'modsSearch',message:'Нашли проект',output:JSON.stringify({results:[{id:'sodium',name:'Sodium'}]})});
  await page.locator('#hz-source').selectOption('modrinth');
  await page.locator('#hz-search').fill('sodium');
  await page.locator('[data-hz="search"]').click();
  const obsolete=await last('hzRun');
  await page.locator('#hz-source').selectOption('curseforge');
  await receive(result(obsolete.requestId));
  assert.equal(await page.locator('.hz-result-card').count(),0,'late search must be discarded');
  assert.match(await page.locator('#hz-status').textContent(),/Параметры поиска изменились/);
  assert.equal(await page.locator('[data-hz="search"]').isEnabled(),true);
  // Actions retain the catalogue that produced the card.
  await page.locator('#hz-source').selectOption('modrinth');
  await page.locator('[data-hz="search"]').click();
  await receive(result((await last('hzRun')).requestId));
  await page.evaluate(()=>{document.querySelector('#hz-source').value='curseforge';});
  await page.locator('.hz-result-card [data-action="modsInstall"]').click();
  const install=await last('hzRun');
  assert.equal(install.source,'modrinth');assert.equal(install.value,'sodium');
  await receive({kind:'hzError',requestId:install.requestId,message:'Не хватает места'});
  await page.locator('#hz-search').fill('iris');
  assert.equal(await page.locator('.hz-result-card').count(),0,'editing query clears old cards');
  await page.locator('[data-hz="search"]').click();
  await receive(result((await last('hzRun')).requestId));
  await page.locator('#hz-filter').selectOption('modpack');
  assert.equal(await page.locator('.hz-result-card').count(),0,'changing kind clears old cards');
  // A stale scan must not undo a newer folder choice in the settings modal.
  await page.locator('[data-hz="scan"]').click();
  const oldScan=await last('hzScan');
  await page.locator('[data-hz="settings"]').click();
  await page.locator('#modal [data-hz="choose"][data-field="packFolder"]').click();
  const choice=await last('hzChoose');
  assert.equal(await page.locator('#modal [data-hz="choose"][data-field="home"]').isDisabled(),true);
  assert.equal(await page.locator('#modal [data-hz="open"]').isDisabled(),true);
  assert.equal(await page.locator('#modal [data-hz="link"]').isDisabled(),true);
  assert.match(await page.locator('#hz-modal-status').textContent(),/Выбери путь/);
  await receive({kind:'hzState',requestId:choice.requestId,...hz,packFolder:'E:\\New Packs'});
  await receive({kind:'hzState',requestId:oldScan.requestId,...hz});
  assert.equal(await page.locator('[data-hz-path="packFolder"]').textContent(),'E:\\New Packs');
  await page.locator('#modal [data-hz="run"]').click();
  const prepare=await last('hzRun');
  await receive({kind:'hzProgress',requestId:prepare.requestId,message:'Готовим файлы',done:1,total:4});
  assert.match(await page.locator('#hz-modal-status').textContent(),/Готовим файлы/);
  await receive({kind:'hzError',requestId:prepare.requestId,message:'Проверь подключение'});
  assert.equal(await page.locator('#hz-modal-status').isVisible(),true);
  assert.match(await page.locator('#hz-modal-status').textContent(),/Проверь подключение/);
  assert.equal(await page.locator('#modal [data-hz="run"]').isEnabled(),true);
  await page.locator('#modal [data-hz="choose"][data-field="home"]').click();
  await receive({kind:'hzDone',requestId:(await last('hzChoose')).requestId,cancelled:true});
  assert.match(await page.locator('#hz-modal-status').textContent(),/Выбор отменён/);
  await close();
  // Shared Minecraft and Horizon documents have independent read-only states.
  await page.locator('[data-hz="scan"]').click();
  await receive({kind:'hzState',requestId:(await last('hzScan')).requestId,...hz,packReadOnly:true,readOnly:false});
  await page.locator('[data-hz="settings"]').click();
  assert.equal(await page.locator('#modal [data-hz="choose"][data-field="packFolder"]').isDisabled(),true);
  assert.equal(await page.locator('#modal [data-hz="choose"][data-field="home"]').isEnabled(),true);
  await page.setViewportSize({width:880,height:640});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth&&document.querySelector('#modal').scrollWidth<=document.querySelector('#modal').clientWidth),true);
  require('node:fs').mkdirSync(path.join(root,'qa'),{recursive:true});
  await page.waitForTimeout(350);
  await page.screenshot({path:path.join(root,'qa/recovery-horizon-settings-small.png')});
  await close();
  // A read started before a toggle cannot turn the switch back on afterward.
  await page.locator('[data-hz="classic"]').click();
  await page.locator('.mc-card [data-mc="mods"]').click();
  const enabled=[{file:'sodium.jar',enabled:true,bytes:1024}];
  const disabled=[{file:'sodium.jar.disabled',enabled:false,bytes:1024}];
  await receive({kind:'mcMods',requestId:(await last('mcMods')).requestId,id:'prism-a',mods:enabled});
  await page.locator('[data-mc="modRefresh"]').click();
  const oldMods=await last('mcMods');
  await page.locator('[data-mc="toggleMod"]').click();
  await receive({kind:'mcDone',requestId:(await last('mcToggleMod')).requestId});
  await receive({kind:'mcMods',id:'prism-a',mods:disabled});
  await receive({kind:'mcMods',requestId:oldMods.requestId,id:'prism-a',mods:enabled});
  assert.equal(await page.locator('[data-mc="toggleMod"]').getAttribute('aria-checked'),'false');
  await close();
  // Reopening the same profile replaces the older read even when the ID matches.
  await page.locator('.mc-card [data-mc="mods"]').click();
  const firstRead=await last('mcMods');await close();
  await page.locator('.mc-card [data-mc="mods"]').click();
  const secondRead=await last('mcMods');
  await receive({kind:'mcMods',requestId:secondRead.requestId,id:'prism-a',mods:disabled});
  await receive({kind:'mcMods',requestId:firstRead.requestId,id:'prism-a',mods:enabled});
  assert.equal(await page.locator('[data-mc="toggleMod"]').getAttribute('aria-checked'),'false');
  await close();assert.deepEqual(errors,[]);
  console.log('Recovery UI: catalogue identity, stale searches/scans/mods, modal feedback, read-only settings and narrow layout passed');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
